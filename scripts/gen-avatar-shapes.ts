/**
 * Generates `crates/avatars/src/shapes.rs` and `crates/avatars/src/presets.rs`
 * from the upstream `bot-avatars` TypeScript sources (MIT, Jakub Antalik).
 *
 * Run with `bun run avatars:shapes`. The upstream files are read from
 * `crates/avatars/upstream/` so the port stays reproducible without network
 * access; refresh those two files to take a new upstream revision.
 */

const ROOT = new URL("..", import.meta.url).pathname;
const UPSTREAM = `${ROOT}crates/avatars/upstream`;

/** The upstream type name and the Rust variant it becomes. */
const VARIANTS: [string, string][] = [
  ["clover", "Clover"],
  ["flower", "Flower"],
  ["triangle", "Triangle"],
  ["square", "Square"],
  ["blob", "Blob"],
  ["ghost", "Ghost"],
  ["circle", "Circle"],
  ["drop", "Drop"],
  ["star", "Star"],
  ["droid", "Droid"],
  ["mech", "Mech"],
  ["alien", "Alien"],
  ["hexagon", "Hexagon"],
  ["cat", "Cat"],
  ["cloud", "Cloud"],
  ["pill", "Pill"],
  ["pebble", "Pebble"],
  ["puddle", "Puddle"],
];

/** The `{ ... }` block an `export const name` is assigned. */
const grab = (source: string, name: string): string => {
  const start = source.indexOf(`export const ${name}`);

  if (start === -1) {
    throw new Error(`missing ${name}`);
  }

  const open = source.indexOf("{", start);
  let depth = 0;

  for (let i = open; i < source.length; i += 1) {
    const char = source[i];

    if (char === "{") {
      depth += 1;
    } else if (char === "}") {
      depth -= 1;

      if (depth === 0) {
        return source.slice(open, i + 1);
      }
    }
  }

  throw new Error(`unterminated ${name}`);
};

/** `key: 'value'` pairs of a generated data block. */
const entries = (block: string): Map<string, string> =>
  new Map(
    [...block.matchAll(/(?<key>\w+):\s*'(?<value>[^']*)'/gu)].map((m) => [
      m.groups?.key ?? "",
      m.groups?.value ?? "",
    ])
  );

/** A Rust float literal: `1` becomes `1.0`. */
const num = (value: string | undefined, fallback = "1.0"): string => {
  const raw = value ?? fallback;

  return raw.includes(".") ? raw : `${raw}.0`;
};

const HEADER = `//! Generated by \`scripts/gen-avatar-shapes.ts\` from the upstream
//! \`bot-avatars\` package (MIT, Jakub Antalik). Do not edit by hand.
`;

const bodySource = async (): Promise<string> => {
  const source = await Bun.file(`${UPSTREAM}/shapes.ts`).text();
  const paths = entries(grab(source, "SHAPE_PATHS"));
  const parts = entries(grab(source, "SHAPE_PARTS"));

  const constants = VARIANTS.flatMap(([key]) => {
    const path = paths.get(key);

    if (!path) {
      throw new Error(`missing path ${key}`);
    }

    const named = `pub const ${key.toUpperCase()}: &str =\n    "${path}";\n`;
    const thin = parts.get(key);

    return thin
      ? [
          named,
          `pub const ${key.toUpperCase()}_PARTS: &str =\n    "${thin}";\n`,
        ]
      : [named];
  });

  const arms = VARIANTS.map(
    ([key, variant]) => `            Self::${variant} => ${key.toUpperCase()},`
  );

  const partArms = VARIANTS.flatMap(([key, variant]) =>
    parts.has(key)
      ? [`            Self::${variant} => Some(${key.toUpperCase()}_PARTS),`]
      : []
  );

  return `${HEADER}//! Body outlines in the 100x100 design box, centred on (50, 50).
//!
//! Generated by \`scripts/gen-avatar-shapes.ts\` from the upstream
//! \`bot-avatars\` package (MIT, Jakub Antalik). Do not edit by hand.

use crate::BotAvatarType;

${constants.join("\n")}
impl BotAvatarType {
    /// The body outline, as SVG path data in the 100x100 box.
    pub const fn path(self) -> &'static str {
        match self {
${arms.join("\n")}
        }
    }

    /// Thin parts (antennae) drawn behind the body at a fraction of its depth.
    pub const fn parts(self) -> Option<&'static str> {
        match self {
${partArms.join("\n")}
            _ => None,
        }
    }
}
`;
};

const presetsSource = async (): Promise<string> => {
  const source = await Bun.file(`${UPSTREAM}/presets.ts`).text();

  const rows = new Map(
    [
      ...grab(source, "botAvatarPresets").matchAll(
        /(?<key>\w+):\s*\{(?<body>[^}]*)\}/gu
      ),
    ].map((m) => [
      m.groups?.key ?? "",
      new Map(
        [
          ...(m.groups?.body ?? "").matchAll(
            /(?<field>\w+):\s*(?:'(?<text>[^']*)'|(?<number>[\d.]+))/gu
          ),
        ].map((f) => [
          f.groups?.field ?? "",
          f.groups?.text ?? f.groups?.number,
        ])
      ),
    ])
  );

  if (rows.size !== 18) {
    throw new Error(`expected 18 presets, got ${rows.size}`);
  }

  const constants = VARIANTS.map(([key]) => {
    const fields = rows.get(key);

    if (!fields) {
      throw new Error(`missing preset ${key}`);
    }

    return `pub const ${key.toUpperCase()}: BotAvatarPreset = BotAvatarPreset {
    label: "${fields.get("label")}",
    color: "#${fields.get("color")?.replace(/^#/u, "")}",
    face: BotAvatarFace::${fields.get("face") === "mouth" ? "Mouth" : "Eyes"},
    face_x: ${num(fields.get("faceX"))},
    face_y: ${num(fields.get("faceY"))},
    face_scale: ${num(fields.get("faceScale"))},
    brightness: ${num(fields.get("brightness"))},
    saturation: ${num(fields.get("saturation"), "1.5")},
};
`;
  });

  const arms = VARIANTS.map(
    ([key, variant]) =>
      `        BotAvatarType::${variant} => ${key.toUpperCase()},`
  );

  return `${HEADER}//! The eighteen types: each body says where its face sits and which colour
//! it ships with.
//!
//! Generated by \`scripts/gen-avatar-shapes.ts\` from the upstream
//! \`bot-avatars\` package (MIT, Jakub Antalik). Do not edit by hand.

use crate::{BotAvatarFace, BotAvatarPreset, BotAvatarType};

${constants.join("\n")}
pub fn preset(kind: BotAvatarType) -> BotAvatarPreset {
    match kind {
${arms.join("\n")}
    }
}
`;
};

/** The two upstream sources, with where they came from. */
const NOTICE = `# Upstream sources

\`shapes.ts\` and \`presets.ts\` are copied unmodified from
[Jakubantalik/Libraries.dev](https://github.com/Jakubantalik/Libraries.dev), package
\`bot-avatars\` (MIT, (c) Jakub Antalik). \`scripts/gen-avatar-shapes.ts\` generates
\`crates/avatars/src/shapes.rs\` and \`crates/avatars/src/presets.rs\` from them.
`;

await Bun.write(`${ROOT}crates/avatars/src/shapes.rs`, await bodySource());

await Bun.write(`${ROOT}crates/avatars/src/presets.rs`, await presetsSource());

await Bun.write(`${UPSTREAM}/NOTICE.md`, NOTICE);

console.log("wrote crates/avatars/src/shapes.rs and presets.rs");
